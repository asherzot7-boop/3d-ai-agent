def build(duty, docs_by_resp):
    out = []
    for name, full, role, room, grp, boss, dk, resp in STAFF:
        g = G[grp]
        d = next((x[1] for x in duty if dk and x[0] == dk), [])
        if grp == 'vac' and name == 'Тожимирзаева Комила':
            d = ['Принимает клиентов по вакцине в комнатах 6 и 7 (вакцинация и процедуры)', 'Принимает оплату за вакцину', 'Делает вакцинацию и наблюдает клиента после прививки']
        days = [list(x) for x in g['days']]
        days[0] = (days[0][0], COMMON_DAY1[:1] + ['Рабочее место: ' + room] + days[0][1]) if grp not in ('house', 'driver') else (days[0][0], days[0][1] + COMMON_DAY1[1:2])
        docs = []
        for r in resp:
            for it in docs_by_resp.get(r, []):
                if it not in docs: docs.append(it)
        out.append(dict(key=name, full=full, role=role, room=room, group=grp, boss=boss, purpose=PURPOSE[grp],
                        duties=d or ['Обязанности не заданы: уточнить у руководителя'], days=[{'t': t, 'tasks': ts} for t, ts in days],
                        safety=g['safety'], docs=docs[:8], quiz=[{'q': q, 'a': a} for q, a in g['quiz']], access=ACCESS[grp], appday=APPDAY[grp],
                        vacancy=name.startswith('Вакансия')))
    return out
